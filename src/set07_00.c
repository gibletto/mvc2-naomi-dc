void set07_00_set( void )
{
	PLAYER_WORK *ew ;
	int i ;

	if( ( ew = work_get( 0, W_SET, LIST_END ) ) ){
		ew->disp_flag = 0 ;
		ew->work_func = set07_00_path_main ;
		ew->obj_flag = OBJ_POS | OBJ_ROT_X | OBJ_ROT_Y | OBJ_ROT_Z | OBJ_BRIGHT ;
		ew->timer1 = 1 ;
		for( i = 0 ; i < 8 ; i ++ ) set07_00_part_make( ew, i ) ;
		set07_00b_set( ew ) ;
	}
}

/* a field of the keys before, at and after key n, mixed by the spline's weights */
#define KEY_MIX( n, f )	( set07_00_key_tbl[( n ) - 1].f * w0 + set07_00_key_tbl[n].f * w1	\
			+ ( set07_00_key_tbl + ( n ) + 1 )->f * w2 )

/*==============================================================*/
static void set07_00_path_main( PLAYER_WORK *ew )
{
	Float w0, w1, w2, t ;
	Sint32 n ;
	VEC3 v, out ;

	t = ( Float )ew->timer0 / ( set07_00_key_tbl[ew->timer1 + 1].time - set07_00_key_tbl[ew->timer1].time ) ;
	spline_weight( &w0, &w1, &w2, t ) ;
	n = ew->timer1 ;
	ew->rot[0] = -DEG_ANG( KEY_MIX( n, rot.x ) ) ;
	ew->rot[1] = -DEG_ANG( KEY_MIX( n, rot.y ) ) ;
	ew->rot[2] = -DEG_ANG( KEY_MIX( n, rot.z ) ) ;
	v.x = KEY_MIX( n, pos.x ) ;
	v.y = KEY_MIX( n, pos.y ) ;
	v.z = KEY_MIX( n, pos.z ) ;
	nlPushMatrix( 0 ) ;
	nlUnitMatrix() ;
	nlRotateAZ( ew->rot[2] ) ;
	nlRotateAY( ew->rot[1] ) ;
	nlRotateAX( ew->rot[0] ) ;
	nlCalcVector( &v, &out ) ;
	nlPopMatrix( 1 ) ;
	ew->pos.x = -out.x ;
	ew->pos.y = -out.y ;
	ew->pos.z = -out.z ;
	ew->timer0 ++ ;
	if( ew->timer0 >= ( set07_00_key_tbl[ew->timer1 + 1].time - set07_00_key_tbl[ew->timer1].time ) ){
		ew->timer0 = 0 ;
		ew->timer1 ++ ;
		if( ( Uint32 )( ew->timer1 + 2 ) >= 89 ) ew->timer1 = 1 ;
	}
}

/*==============================================================*/
/*			The eight models ride on the path's matrix			*/
/*==============================================================*/
static void set07_00_part_make( PLAYER_WORK *pl_w, int no )
{
	PLAYER_WORK *ew ;

	if( ( ew = work_get( 0, W_SET, LIST_END ) ) ){
		ew->disp_flag = 1 ;
		ew->work_func = set07_00_path_main ;
		ew->obj = obj_stg->obj[no + 1] ;
		ew->obj_flag = OBJ_BRIGHT ;
		ew->ef_w = pl_w ;
		ew->base_mtx = &pl_w->obj_mtx ;
		ew->type = no ;
	}
}

