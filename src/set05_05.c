static void set05_05_main( PLAYER_WORK *ew )
{
	Float w0, w1, w2 ;
	Sint32 cnt = set05_05_cnt_tbl[ew->type] ;
	VEC3 *pts = set05_05_path_tbl[ew->type] ;
	Sint32 n ;

	ew->obj = *( obj_stg->obj + set05_05_obj_tbl[( Uint32 )Sys->game_timer % 18] + 18 ) ;
	spline_weight( ( Float )ew->timer0 / 50.0f, &w0, &w1, &w2 ) ;
	n = ew->timer1 ;
	ew->pos.x = pts[n - 1].x * w0 + pts[n].x * w1 + ( pts + n )[1].x * w2 ;
	ew->pos.y = pts[n - 1].y * w0 + pts[n].y * w1 + ( pts + n )[1].y * w2 ;
	ew->pos.z = pts[n - 1].z * w0 + pts[n].z * w1 + ( pts + n )[1].z * w2 ;
	if( ++ ew->timer0 >= 50 ){
		ew->timer0 = 0 ;
		if( ++ ew->timer1 + 1 >= cnt ) ew->timer1 = 1 ;
	}
}

/*==============================================================*/
static void set05_05_make( int no )
{
	PLAYER_WORK *ew ;

	if( ( ew = work_get( 0, W_SET, LIST_END ) ) ){
		ew->disp_flag = 1 ;
		ew->work_func = set05_05_main ;
		ew->obj = obj_stg->obj[18] ;
		ew->obj_flag = OBJ_POS | OBJ_BRIGHT ;
		ew->type = no ;
		ew->timer1 = 1 ;
	}
}

/****************************************************************/
void set05_05_set( void )
{
	int i ;

	for( i = 0 ; i < 2 ; i ++ ) set05_05_make( i ) ;
}

